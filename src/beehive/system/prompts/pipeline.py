"""管线恢复与纯脚本产物验收的固定提示词。"""

PIPELINE_RESUME_PROMPT = "请继续未完成的流程（审批后或中断后续）。"


def script_acceptance_prompt(goal, output):
    return (
        "脚本管线已完成，请简短验收交付物：先检查 output/ 中与目标相关的文件，"
        "读取并确认内容符合目标；符合就立即结束，只用一句话报告文件和结果。"
        "若 output/ 中没有合适文件，再检查项目根目录（临时脚本与中间材料所在）；找到符合目标的材料就移入 output/，"
        "然后结束并简短报告。只有两处都没有可用材料，或材料不符合目标时，才接管任务排查并补齐；"
        "不要重复描述检查过程，也不要在验收通过后继续分析或提出额外补救。\n\n"
        f"用户目标：{goal}\n脚本结果：{output or '（无文本输出）'}"
    )
